CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    name_key VARCHAR(80) NOT NULL UNIQUE,
    version BIGINT NOT NULL DEFAULT 0
);

INSERT INTO departments (name, name_key)
SELECT MIN(TRIM(department)), LOWER(TRIM(department)) FROM employees GROUP BY LOWER(TRIM(department));

UPDATE employees SET department = (
    SELECT d.name FROM departments d WHERE d.name_key = LOWER(TRIM(employees.department))
);
